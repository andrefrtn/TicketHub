async function call({ cookie, id, ...body } = {}, status = 200) {
  const post = Boolean(body.action);
  const url = `${base}/api/helpdesk${id && !post ? `?id=${id}` : ""}`;
  const headers = { ...(cookie ? { Cookie: cookie } : {}), ...(post ? { "Content-Type": "application/json", Origin: base } : {}) };
  const result = await fetch(url, post ? { method: "POST", headers, body: JSON.stringify({ ...body, id }) } : { headers });
  const json = await result.json();
  assert.equal(result.status, status, JSON.stringify(json));
  return { ...json, cookie: result.headers.get("set-cookie")?.split(";")[0] };
}

